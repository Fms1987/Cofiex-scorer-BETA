"""Merge fichas/pleitos and fichas/avaliacoes into per-sector files, for platforms with a
file-count limit (e.g. claude.ai's native Skill uploader: max 200 files).

This does NOT replace fichas/ — it is a build step for a separate claude.ai package. The
Claude Code / GitHub skill keeps one file per ficha; this script produces a parallel,
consolidated copy under <out_dir>/fichas-merged/{pleitos,avaliacoes}/<sector>.md.

Each original record is kept byte-for-byte (including its own YAML header), preceded by a
boundary marker comment with the original filename, so line-anchored Grep patterns
(e.g. ^sector_verified: <sector>$) still match once per record -- use `count` mode (not
`files_with_matches`) to get n, since many records now share one file.

Usage: python tools/merge_fichas_for_claudeai.py <root>
  <root> = the skill directory containing fichas/ (e.g. skills/cofiex-scorer)
"""
import sys
from pathlib import Path


def sector_of_pleito(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("sector_verified:"):
            return line.split(":", 1)[1].strip()
    for line in text.splitlines():
        if line.startswith("sector:"):
            return line.split(":", 1)[1].strip()
    return "other"


def sector_of_avaliacao(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("sector:"):
            return line.split(":", 1)[1].strip()
    return "other"


def merge(src_dir: Path, dest_dir: Path, sector_fn):
    dest_dir.mkdir(parents=True, exist_ok=True)
    buckets: dict[str, list[str]] = {}
    for f in sorted(src_dir.glob("*.md")):
        text = f.read_text(encoding="utf-8")
        sector = sector_fn(text) or "other"
        buckets.setdefault(sector, []).append(f"<!-- ficha:{f.name} -->\n{text.rstrip()}\n")
    for sector, records in buckets.items():
        out = dest_dir / f"{sector}.md"
        header = (
            f"<!-- Merged ficha file for claude.ai (file-count-limited platform). "
            f"{len(records)} records. Generated by tools/merge_fichas_for_claudeai.py -- "
            f"do not hand-edit; regenerate from fichas/ instead. -->\n\n"
        )
        out.write_text(header + "\n\n".join(records) + "\n", encoding="utf-8")
        print(f"{dest_dir.name}/{sector}.md: {len(records)} records")


def main():
    root = Path(sys.argv[1])
    merge(root / "fichas" / "pleitos", root / "fichas-merged" / "pleitos", sector_of_pleito)
    merge(root / "fichas" / "avaliacoes", root / "fichas-merged" / "avaliacoes", sector_of_avaliacao)


if __name__ == "__main__":
    main()
